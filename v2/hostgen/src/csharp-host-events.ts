import { promises as fs } from "node:fs";
import path from "node:path";
import { listHostEventMethods, type NormalizedHostEventMethod } from "@effindomv2/runtime/managed-harness/host-events";
import { loadModuleExport, sourcePathForHeader } from "./common";
import { csharpTypeName, groupByService, pascalCase } from "./csharp-host-services";

export interface CSharpHostEventsOptions {
  /** The namespace of the generated C# classes. */
  readonly namespace: string;
}

function delegateType(method: NormalizedHostEventMethod): string {
  return method.args.length === 0 ? "Action" : `Action<${method.args.map((type) => csharpTypeName(type)).join(", ")}>`;
}

function renderCSharp(methods: readonly NormalizedHostEventMethod[], header: string, options: CSharpHostEventsOptions): string {
  const lines = [
    "// <auto-generated/>",
    header,
    "#nullable enable",
    "",
    "using System;",
    "using System.Runtime.InteropServices.JavaScript;",
    "",
    `namespace ${options.namespace};`,
  ];
  for (const [serviceName, serviceMethods] of groupByService(methods)) {
    lines.push("", `/// <summary>The <c>${serviceName}</c> host events.</summary>`, `public static partial class ${pascalCase(serviceName)}`, "{");
    serviceMethods.forEach((method, index) => {
      const eventName = pascalCase(method.methodName);
      const parameters = method.args.map((type, argIndex) => `${csharpTypeName(type)} arg${String(argIndex)}`);
      const values = method.args.map((_type, argIndex) => `arg${String(argIndex)}`);
      if (index > 0) {
        lines.push("");
      }
      lines.push(
        `    /// <summary>Raised when the host emits <c>${serviceName}.${method.methodName}</c>.</summary>`,
        `    public static event ${delegateType(method)}? ${eventName};`,
        "",
        `    [JSExport("${method.exportName}")]`,
        `    internal static void On${eventName}(${parameters.join(", ")}) => ${eventName}?.Invoke(${values.join(", ")});`,
      );
    });
    lines.push("}");
  }
  return `${lines.join("\n")}\n`;
}

/** Renders the C# events and the [JSExport] functions that raise them for the host events `exportName` of `modulePath`. */
export async function renderCSharpHostEvents(
  modulePath: string,
  exportName: string,
  options: CSharpHostEventsOptions,
): Promise<string> {
  const registry = await loadModuleExport(modulePath, exportName, "fui-host-events-");
  const methods = listHostEventMethods(registry as never);
  return renderCSharp(methods, `// Generated by hostgen from ${sourcePathForHeader(modulePath)}#${exportName}.`, options);
}

export async function generateCSharpHostEventsFile(
  modulePath: string,
  exportName: string,
  outputPath: string,
  options: CSharpHostEventsOptions,
): Promise<void> {
  const csharp = await renderCSharpHostEvents(modulePath, exportName, options);
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, csharp, "utf8");
}
