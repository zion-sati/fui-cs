import { promises as fs } from "node:fs";
import path from "node:path";
import {
  listHostServiceMethods,
  type HostServiceTypeName,
  type NormalizedHostServiceMethod,
} from "@effindomv2/runtime/managed-harness/host-services";
import { loadModuleExport, sourcePathForHeader } from "./common";

export interface CSharpHostServicesOptions {
  /** The namespace of the generated C# classes. */
  readonly namespace: string;
  /** The JSImport module name the application declares for the generated JavaScript module. */
  readonly jsModuleName: string;
  /** The import path from the generated JavaScript module to the fui-cs host-service runtime. */
  readonly runtimeImport: string;
  /**
   * For a worker's host services, the import path from the generated JavaScript module to the definitions: the
   * module then runs the services inside the worker instead of calling the page through the managed harness.
   */
  readonly workerDefinitionsImport?: string;
}

export interface CSharpHostServicesOutput {
  readonly csharp: string;
  readonly module: string;
}

export function csharpTypeName(type: HostServiceTypeName): string {
  switch (type) {
    case "string":
      return "string";
    case "bool":
      return "bool";
    case "i32":
      return "int";
    case "u32":
      return "uint";
    case "i64":
      return "long";
    case "u64":
      return "ulong";
    case "f64":
      return "double";
    case "bytes":
      return "byte[]";
    case "i32_array":
      return "int[]";
    case "u32_array":
      return "uint[]";
    case "i64_array":
      return "long[]";
    case "u64_array":
      return "ulong[]";
    case "f64_array":
      return "double[]";
    case "void":
      return "void";
  }
}

/** The JavaScript value NetWasm marshals each type to and from. */
function typeScriptTypeName(type: HostServiceTypeName): string {
  switch (type) {
    case "string":
      return "string";
    case "bool":
      return "boolean";
    case "i64":
    case "u64":
      return "bigint";
    case "bytes":
      return "Uint8Array";
    case "i32_array":
      return "Int32Array";
    case "u32_array":
      return "Uint32Array";
    case "i64_array":
      return "BigInt64Array";
    case "u64_array":
      return "BigUint64Array";
    case "f64_array":
      return "Float64Array";
    case "void":
      return "void";
    default:
      return "number";
  }
}

export function pascalCase(value: string): string {
  return value.length === 0 ? value : `${value.slice(0, 1).toUpperCase()}${value.slice(1)}`;
}

/** Groups methods by service, keeping each service's first appearance in the sorted method list. */
export function groupByService<T extends { readonly serviceName: string }>(methods: readonly T[]): ReadonlyMap<string, readonly T[]> {
  const services = new Map<string, T[]>();
  for (const method of methods) {
    const group = services.get(method.serviceName);
    if (group === undefined) {
      services.set(method.serviceName, [method]);
    } else {
      group.push(method);
    }
  }
  return services;
}

function renderCSharp(
  methods: readonly NormalizedHostServiceMethod[],
  header: string,
  options: CSharpHostServicesOptions,
): string {
  const lines = [
    "// <auto-generated/>",
    header,
    "#nullable enable",
    "",
    "using System.Runtime.InteropServices.JavaScript;",
    "",
    `namespace ${options.namespace};`,
  ];
  for (const [serviceName, serviceMethods] of groupByService(methods)) {
    lines.push("", `/// <summary>The <c>${serviceName}</c> host services.</summary>`, `public static partial class ${pascalCase(serviceName)}`, "{");
    serviceMethods.forEach((method, index) => {
      const parameters = method.args.map((type, argIndex) => `${csharpTypeName(type)} arg${String(argIndex)}`);
      if (index > 0) {
        lines.push("");
      }
      lines.push(
        `    /// <summary>Calls the <c>${serviceName}.${method.methodName}</c> host service.</summary>`,
        `    [JSImport("${method.importName}", "${options.jsModuleName}")]`,
        `    public static extern ${csharpTypeName(method.returns)} ${pascalCase(method.methodName)}(${parameters.join(", ")});`,
      );
    });
    lines.push("}");
  }
  return `${lines.join("\n")}\n`;
}

function renderModule(
  methods: readonly NormalizedHostServiceMethod[],
  header: string,
  options: CSharpHostServicesOptions,
): string {
  const lines = [
    header,
    `// JSImport module \`${options.jsModuleName}\`: the application's host services, called through the managed harness.`,
    "",
    `import { callHostService } from '${options.runtimeImport}';`,
  ];
  for (const method of methods) {
    const parameters = method.args.map((type, index) => `arg${String(index)}: ${typeScriptTypeName(type)}`);
    const types = method.args.map((type) => `'${type}'`).join(", ");
    const values = method.args.map((_type, index) => `arg${String(index)}`).join(", ");
    const call = `callHostService('${method.importName}', [${types}], [${values}], '${method.returns}')`;
    const returnType = typeScriptTypeName(method.returns);
    lines.push(
      "",
      `export function ${method.importName}(${parameters.join(", ")}): ${returnType} {`,
      method.returns === "void" ? `  ${call};` : `  return ${call} as ${returnType};`,
      "}",
    );
  }
  return `${lines.join("\n")}\n`;
}

// A worker's module runs the definitions' implementations itself: NetWasm hands a worker's JSImport the same
// JavaScript values (strings, numbers, bigints, booleans, typed arrays) the definitions take and return.
function renderWorkerModule(header: string, exportName: string, definitionsImport: string, options: CSharpHostServicesOptions): string {
  return [
    header,
    `// JSImport module \`${options.jsModuleName}\`: the worker's host services, which run inside the worker.`,
    "",
    `import { workerHostServiceImports } from '${options.runtimeImport}';`,
    `import { ${exportName} } from '${definitionsImport}';`,
    "",
    "export function createWorkerImports(): Record<string, (...args: never[]) => unknown> {",
    `  return workerHostServiceImports(${exportName});`,
    "}",
    "",
  ].join("\n");
}

/** Renders the C# bindings and the JSImport module for the host services `exportName` of `modulePath`. */
export async function renderCSharpHostServices(
  modulePath: string,
  exportName: string,
  options: CSharpHostServicesOptions,
): Promise<CSharpHostServicesOutput> {
  const registry = await loadModuleExport(modulePath, exportName, "fui-host-services-");
  const methods = listHostServiceMethods(registry as never);
  const header = `// Generated by hostgen from ${sourcePathForHeader(modulePath)}#${exportName}.`;
  const module = options.workerDefinitionsImport === undefined
    ? renderModule(methods, header, options)
    : renderWorkerModule(header, exportName, options.workerDefinitionsImport, options);
  return { csharp: renderCSharp(methods, header, options), module };
}

export async function generateCSharpHostServicesFiles(
  modulePath: string,
  exportName: string,
  csharpOutputPath: string,
  moduleOutputPath: string,
  options: CSharpHostServicesOptions,
): Promise<void> {
  const output = await renderCSharpHostServices(modulePath, exportName, options);
  await fs.mkdir(path.dirname(csharpOutputPath), { recursive: true });
  await fs.writeFile(csharpOutputPath, output.csharp, "utf8");
  await fs.mkdir(path.dirname(moduleOutputPath), { recursive: true });
  await fs.writeFile(moduleOutputPath, output.module, "utf8");
}
