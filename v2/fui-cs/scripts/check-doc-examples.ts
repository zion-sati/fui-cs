// Writes every C# example in the public guides (docs/v2/fui-cs/*.md) into a compile-only project, so the build can
// prove the examples still compile against the SDK. Type declarations go to file level and statements into an
// async method; a guide's examples share a namespace. An HTML comment on the line before a block configures it:
//
//   <!-- example: skip -->                          the block is a fragment (shown inside other code, or using
//                                                   generated bindings) and is not compiled
//   <!-- example: worker -->                        the block is worker-project code, compiled with FuiCs.Workers
//   <!-- example: Checkbox checkbox, Action Save --> the variables the block assumes, as the method's parameters
//
// Usage: check-doc-examples <docs directory> <project directory>

import { promises as fs } from 'node:fs';
import path from 'node:path';

import { parseCommandLine } from './hostgen-cli.ts';

const USAGE = 'Usage: check-doc-examples <docs directory> <project directory>';

const PROJECT = `<Project Sdk="NetWasm.Sdk">

  <!-- Generated by scripts/check-doc-examples.ts: the guides' C# examples, compiled against the SDK. -->
  <PropertyGroup>
    <TargetFramework>net11.0</TargetFramework>
    <OutputType>Library</OutputType>
    <Nullable>enable</Nullable>
    <ImplicitUsings>disable</ImplicitUsings>
    <TreatWarningsAsErrors>true</TreatWarningsAsErrors>
    <!-- Examples need not await, use every variable or call every local function. -->
    <NoWarn>$(NoWarn);CS1998;CS0168;CS0219;CS8321;CS0162</NoWarn>
  </PropertyGroup>

  <ItemGroup>
    <ProjectReference Include="../../src/FuiCs/FuiCs.csproj" />
    <ProjectReference Include="../../src/FuiCs.Worker/FuiCs.Worker.csproj" />
  </ItemGroup>

</Project>
`;

interface Example {
  readonly doc: string;
  readonly line: number;
  readonly code: string;
  readonly worker: boolean;
  readonly parameters: string;
}

const DECLARATION = /^(?:using\s|namespace\s|\[|(?:(?:public|internal|private|static|sealed|abstract|partial|readonly|file)\s+)*(?:class|record|struct|interface|enum)\s)/;

function examplesIn(doc: string, text: string): Example[] {
  const examples: Example[] = [];
  const lines = text.split('\n');
  for (let index = 0; index < lines.length; index += 1) {
    if ((lines[index] ?? '').trim() !== '```csharp') continue;
    let previous = index - 1;
    while (previous >= 0 && (lines[previous] ?? '').trim() === '') previous -= 1;
    const directive = /^<!--\s*example:\s*(.*?)\s*-->$/.exec((lines[previous] ?? '').trim())?.[1] ?? '';
    const start = index + 1;
    let end = start;
    while (end < lines.length && (lines[end] ?? '').trim() !== '```') end += 1;
    index = end;
    if (directive === 'skip') continue;
    examples.push({
      doc,
      line: start + 1,
      code: lines.slice(start, end).join('\n'),
      worker: directive === 'worker',
      parameters: directive === 'worker' ? '' : directive,
    });
  }
  return examples;
}

/** Splits a block into its top-level declarations and its statements, by brace depth outside strings. */
function split(code: string): { readonly declarations: string; readonly statements: string } {
  const declarations: string[] = [];
  const statements: string[] = [];
  let group: string[] = [];
  let groupIsDeclaration = false;
  let depth = 0;
  let opened = false;
  for (const line of code.split('\n')) {
    if (group.length === 0) {
      if (line.trim() === '' || line.trim().startsWith('//')) {
        (groupIsDeclaration ? declarations : statements).push(line);
        continue;
      }
      groupIsDeclaration = DECLARATION.test(line.trim());
      opened = false;
    }
    group.push(line);
    for (const character of line.replace(/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)'/g, '""')) {
      if (character === '{') {
        depth += 1;
        opened = true;
      } else if (character === '}') {
        depth -= 1;
      }
    }
    const trimmed = line.trim();
    const complete = depth === 0 && (groupIsDeclaration
      ? (opened && trimmed.endsWith('}')) || trimmed.endsWith(';') || trimmed.endsWith(']')
      : trimmed.endsWith(';') || trimmed.endsWith('}'));
    if (complete) {
      (groupIsDeclaration ? declarations : statements).push(...group);
      group = [];
    }
  }
  (groupIsDeclaration ? declarations : statements).push(...group);
  return { declarations: declarations.join('\n').trim(), statements: statements.join('\n').trim() };
}

function render(example: Example, className: string): string {
  const { declarations, statements } = split(example.code);
  const usings = ['System', 'System.Collections.Generic', 'System.Threading', 'System.Threading.Tasks', example.worker ? 'FuiCs.Workers' : 'FuiCs'];
  // Not marked auto-generated, which would silence the warnings an example should not raise. A guide's examples
  // share a namespace, unless one declares its own, so later examples can use earlier ones' types.
  const ownNamespace = /^namespace\s/m.test(declarations);
  const guideNamespace = example.doc.replace(/\.md$/, '').replace(/\W/g, '_');
  const lines = [
    `// Generated from ${example.doc}, line ${String(example.line)}, by scripts/check-doc-examples.ts.`,
    ...usings.map((name) => `using ${name};`),
    '',
    ...(ownNamespace ? [] : [`namespace DocExamples.${guideNamespace};`, '']),
  ];
  if (declarations.length > 0) lines.push(declarations, '');
  if (statements.length > 0) {
    lines.push(
      `internal static class ${className}`,
      '{',
      `    internal static async Task Run(${example.parameters})`,
      '    {',
      ...statements.split('\n').map((line) => (line.length > 0 ? `        ${line}` : line)),
      '    }',
      '}',
      '',
    );
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

async function main(): Promise<void> {
  const commandLine = parseCommandLine(process.argv.slice(2), USAGE, 2);
  const [docsDir = '', projectDir = ''] = commandLine.positional;
  const docs = (await fs.readdir(docsDir)).filter((file) => file.endsWith('.md')).sort();
  await fs.rm(projectDir, { recursive: true, force: true });
  await fs.mkdir(projectDir, { recursive: true });
  await fs.writeFile(path.join(projectDir, 'DocExamples.csproj'), PROJECT, 'utf8');
  let count = 0;
  for (const doc of docs) {
    for (const example of examplesIn(doc, await fs.readFile(path.join(docsDir, doc), 'utf8'))) {
      const name = `${doc.replace(/\.md$/, '').replace(/\W/g, '_')}_Line${String(example.line)}`;
      await fs.writeFile(path.join(projectDir, `${name}.cs`), render(example, name), 'utf8');
      count += 1;
    }
  }
  console.log(`${String(count)} examples written to ${path.relative(process.cwd(), projectDir)}.`);
}

await main();
