using System.Runtime.InteropServices.JavaScript;
using System.Threading.Tasks;

namespace FuiCs.Workers.Hosting;

/// <summary>
/// A fui-cs worker project's exports, compiled into each worker project by FuiCs.Exports.targets: the page's worker
/// client runs an entry through <c>__fui_worker_run</c>, whose result is the job's, and stops it through
/// <c>__fui_worker_cancel</c> while the run is in progress.
/// </summary>
public static partial class WorkerExports
{
    [JSExport("__fui_worker_run")]
    public static Task<string> Run(string entryName, string input) =>
        WorkerHosting.Run(JsWorkerHost.Instance, Register, entryName, input);

    [JSExport("__fui_worker_cancel")]
    public static void Cancel() => WorkerHosting.Cancel();

    private static WorkerEntries Register()
    {
        var entries = new WorkerEntries();
        RegisterEntries(entries);
        return entries;
    }

    // Generated by FuiCs.Exports.targets: calls the worker project's FuiWorker.Register(entries).
    static partial void RegisterEntries(WorkerEntries entries);
}

internal sealed class JsWorkerHost : IWorkerHost
{
    public static JsWorkerHost Instance { get; } = new();

    public void ReportProgress(string progress) => Notify("progress", progress);

    public Task<string> FetchAsync(uint requestId, string method, string url, string headers, byte[] body) =>
        FetchImport(requestId, method, url, headers, body);

    public void CancelFetch(uint requestId) => AbortFetch(requestId);

    [JSImport("fetch", "fui_worker_host")]
    private static extern Task<string> FetchImport(uint requestId, string method, string url, string headers, byte[] body);

    [JSImport("abortFetch", "fui_worker_host")]
    private static extern void AbortFetch(uint requestId);

    [JSImport("notify", "fui_worker_host")]
    private static extern void Notify(string operation, string text);
}
